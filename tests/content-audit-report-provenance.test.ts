async function setup(fn) {
  const root = await mkdtemp(join(tmpdir(), "report-provenance-"));
  try {
    const sample = JSON.parse(
      await readFile(
        "skills/content-search-audit/examples/enterprise-browser-capture.json",
        "utf8",
      ),
    );
    sample.entry.source.sourceId = "PRIVATE_ORIGIN_CANARY";
    const initial = resolveAuditContext(sample.config, []);
    await saveEnterpriseRun(join(root, "initial"), initial);
    await importEnterpriseBrowserCaptures(
      join(root, "initial"),
      {
        sourceDigest: enterpriseDigest(initial),
        newRunId: "captured",
        assessmentAt: initial.assessmentAt,
        captures: [sample.entry],
      },
      join(root, "run"),
    );
    const run = await loadEnterpriseRun(join(root, "run"));
    const metadata = {
      sourceRunDigest: enterpriseDigest(run),
      revisionId: "r1",
      authorId: "author",
      generatedAt: run.assessmentAt,
      brand: { name: "Synthetic", accent: "#174f7b" },
    };
    await buildStoredEnterpriseReport(
      join(root, "run"),
      metadata,
      join(root, "report"),
    );
    await fn({
      run,
      metadata,
      report: await loadEnterpriseReport(join(root, "report")),
    });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}
it("replays every generated item and binds its owner and source without copying payloads", async () =>
  setup(async ({ run, report }) => {
    const result = await inspectGeneratedReportProvenance(run, report);
    expect(result.items).toHaveLength(
      report.observations.length + report.narrative.length,
    );
    expect(result.items.every((i) => i.origin.moduleId === "browser")).toBe(
      true,
    );
    expect(
      result.items.every(
        (i) => i.origin.sourceRunDigest === enterpriseDigest(run),
      ),
    ).toBe(true);
    expect(
      result.items.every((i) => i.origin.evidenceBindings.length > 0),
    ).toBe(true);
    expect(JSON.stringify(result)).not.toContain("PRIVATE_ORIGIN_CANARY");
    expect(JSON.stringify(result)).not.toContain("artifactText");
    expect(result).toMatchObject({
      audience: "private",
      persistenceAuthorized: false,
      disclosureAuthorized: false,
      historyPreserved: false,
    });
    expect(await inspectGeneratedReportProvenance(run, report)).toEqual(result);
  }));
