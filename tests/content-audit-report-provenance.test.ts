it("binds generated findings to their owning SEO checks and evidence context", async () => {
  const root = await mkdtemp(join(tmpdir(), "finding-provenance-"));
  try {
    const bundle = JSON.parse(
      await readFile(
        "skills/content-search-audit/examples/enterprise-technical-seo-evaluations.json",
        "utf8",
      ),
    );
    const initial = resolveAuditContext(
      {
        customerId: "customer",
        runId: "initial",
        assessmentAt: bundle.assessmentAt,
        profileIds: ["commerce"],
        entities: [{ entityId: "site", type: "site" }],
      },
      [],
    );
    bundle.sourceDigest = enterpriseDigest(initial);
    bundle.evaluations[0].context.expectedCanonical =
      "https://example.com/expected";
    await saveEnterpriseRun(join(root, "initial"), initial);
    await evaluateEnterpriseTechnicalSeo(
      join(root, "initial"),
      bundle,
      join(root, "run"),
    );
    const run = await loadEnterpriseRun(join(root, "run"));
    const metadata = {
      sourceRunDigest: enterpriseDigest(run),
      revisionId: "r1",
      authorId: "author",
      generatedAt: run.assessmentAt,
      brand: { name: "Synthetic", accent: "#174f7b" },
    };
    await buildStoredEnterpriseReport(
      join(root, "run"),
      metadata,
      join(root, "report"),
    );
    const report = await loadEnterpriseReport(join(root, "report"));
    expect(report.findings.length).toBeGreaterThan(0);
    const result = await inspectGeneratedReportProvenance(run, report);
    for (const finding of report.findings) {
      const item = result.items.find(
        (i) => i.collection === "findings" && i.itemId === finding.findingId,
      );
      expect(item.origin.moduleId).toBe("technical-seo");
      expect(item.targetDigest).toBe(
        enterpriseReviewTargetDigest(report, "finding", finding.findingId),
      );
      expect(item.origin.evidenceBindings.map((e) => e.evidenceId)).toEqual(
        [
          ...new Set([
            ...finding.evidenceIds,
            ...run.checks.find((c) => c.checkId === finding.checkId)
              .dependencies,
          ]),
        ].sort(),
      );
    }
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

it("binds one immutable input snapshot across asynchronous compiler checks", async () =>
  setup(async ({ run, report }) => {
    const reportDigest = enterpriseDigest(report),
      sourceDigest = enterpriseDigest(run);
    const pending = inspectGeneratedReportProvenance(run, report);
    report.narrative[0].text = "UNREPLAYED_MUTATION";
    report.revisionId = "mutated";
    run.customerId = "mutated";
    const result = await pending;
    expect(result.reportDigest).toBe(reportDigest);
    expect(result.revisionId).toBe("r1");
    expect(
      result.items.every((i) => i.origin.sourceRunDigest === sourceDigest),
    ).toBe(true);
    expect(JSON.stringify(result)).not.toContain("UNREPLAYED_MUTATION");
    expect(result.scope.customerId).not.toBe("mutated");
  }));

function storedBinding({ root, run, report, receipt }) {
  return {
    sourceDirectory: join(root, "run"),
    reportDirectory: join(root, "report"),
    sourceRunDigest: enterpriseDigest(run),
    reportDigest: enterpriseDigest(report),
    manifestDigest: receipt.manifestDigest,
  };
}
it("binds provenance to the validated report manifest and canonical file bytes", async () =>
  setup(async (f) => {
    const result = await inspectStoredGeneratedReportProvenance(
      storedBinding(f),
    );
    expect(result.reportDigest).toBe(enterpriseDigest(f.report));
    expect(result.artifactBinding).toEqual({
      manifestDigest: f.receipt.manifestDigest,
      reportJsonDigest: f.receipt.reportDigest,
      edition: "customer",
      sourceRunDigest: enterpriseDigest(f.run),
    });
    expect(result.disclosureAuthorized).toBe(false);
    expect(JSON.stringify(result)).not.toContain(f.root);
  }));
